const DICTS = { fr: FR, es: ES };
let lang = 'fr';
try { const s = localStorage.getItem('sporoto.lang'); if (s && DICTS[s]) lang = s; } catch (e) { /* stockage indisponible */ }

export function t(key) { return DICTS[lang][key] ?? FR[key] ?? key; }
export function getLang() { return lang; }
export function setLang(l) {
  if (!DICTS[l]) return;
  lang = l;
  try { localStorage.setItem('sporoto.lang', l); } catch (e) { /* ignore */ }
  document.documentElement.lang = l;
  applyI18n();
}
export function applyI18n(root = document) {
  root.querySelectorAll('[data-i18n]').forEach(el => { el.textContent = t(el.dataset.i18n); });
  root.querySelectorAll('[data-i18n-title]').forEach(el => { el.title = t(el.dataset.i18nTitle); });
}
